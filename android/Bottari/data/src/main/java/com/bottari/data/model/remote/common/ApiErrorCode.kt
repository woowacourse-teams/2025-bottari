package com.bottari.data.model.remote.common

import com.bottari.domain.model.exception.BottariException

enum class ApiErrorCode {
    // ===== MEMBER 관련 =====
    MEMBER_NOT_FOUND, // 404
    MEMBER_NAME_ALREADY_EXISTS, // 409
    MEMBER_SSAID_ALREADY_EXISTS, // 409
    MEMBER_NAME_UNCHANGED, // 400
    MEMBER_NAME_TOO_SHORT, // 400
    MEMBER_NAME_TOO_LONG, // 400
    MEMBER_NAME_OFFENSIVE,
    MEMBER_NAME_GENERATION_FAILED,
    MEMBER_IDENTIFIER_NOT_FOUND_IN_REQUEST,

    // ===== BOTTARI 관련 =====
    BOTTARI_NOT_FOUND, // 404
    BOTTARI_NOT_OWNED, // 403

    // ===== BOTTARI TITLE 관련 =====
    BOTTARI_TITLE_UNCHANGED, // 400
    BOTTARI_TITLE_BLANK, // 400
    BOTTARI_TITLE_TOO_LONG, // 400
    BOTTARI_TITLE_OFFENSIVE,

    // ===== ITEM_NAME 관련 =====
    ITEM_NAME_BLANK, // 400
    ITEM_NAME_TOO_LONG, // 400
    ITEM_NAME_OFFENSIVE,

    // ===== BOTTARI_ITEM 관련 =====
    BOTTARI_ITEM_NOT_FOUND, // 404
    BOTTARI_ITEM_ALREADY_EXISTS, // 409
    BOTTARI_ITEM_DUPLICATE_IN_REQUEST, // 400
    BOTTARI_ITEM_MAXIMUM_EXCEEDED, // 400
    BOTTARI_ITEM_NOT_IN_BOTTARI, // 400
    BOTTARI_ITEM_ALREADY_CHECKED, // 404
    BOTTARI_ITEM_ALREADY_UNCHECKED, // 404
    BOTTARI_ITEM_CHECK_STATE_INVALID,
    BOTTARI_ITEM_NOT_OWNED,

    // ===== BOTTARI_TEMPLATE 관련 =====
    BOTTARI_TEMPLATE_NOT_FOUND, // 404
    BOTTARI_TEMPLATE_NOT_OWNED, // 403
    BOTTARI_TEMPLATE_TITLE_BLANK, // 400
    BOTTARI_TEMPLATE_TITLE_TOO_LONG, // 400
    BOTTARI_TEMPLATE_TITLE_OFFENSIVE,
    BOTTARI_TEMPLATE_INVALID_SORT_TYPE, // 400

    // ===== BOTTARI_TEMPLATE_ITEM 관련 =====
    BOTTARI_TEMPLATE_ITEM_DUPLICATE_IN_REQUEST, // 400

    // ===== TEAM_BOTTARI 관련 =====
    TEAM_BOTTARI_NOT_FOUND, // 404

    // ===== TEAM_BOTTARI_ITEM 관련 =====
    TEAM_BOTTARI_ITEM_NOT_FOUND, // 400
    TEAM_BOTTARI_ITEM_NAME_BLANK, // 400
    TEAM_BOTTARI_ITEM_NAME_TOO_LONG, // 400
    TEAM_BOTTARI_ITEM_ALREADY_EXISTS, // 409
    TEAM_BOTTARI_ITEM_NOT_OWNED, // 403
    TEAM_BOTTARI_ITEM_ALREADY_CHECKED, // 409
    TEAM_BOTTARI_ITEM_ALREADY_UNCHECKED, // 409
    TEAM_BOTTARI_ITEM_NO_ASSIGNED_MEMBERS, // 400
    TEAM_BOTTARI_ITEM_INAPPROPRIATE_TYPE, // 400

    // ===== TEAM_BOTTARI_ITEM_INFO 관련 =====
    TEAM_BOTTARI_ITEM_INFO_NOT_FOUND, // 400

    // ===== TEAM_MEMBER 관련 =====
    TEAM_MEMBER_NOT_FOUND,
    MEMBER_NOT_IN_TEAM_BOTTARI, // 403
    MEMBER_ALREADY_IN_TEAM_BOTTARI, // 409
    TEAM_MEMBER_ALREADY_CHECKED_ALL, // 409
    CANNOT_SEND_REMIND_TO_SELF, // 400

    // ===== ALARM 관련 =====
    ALARM_NOT_FOUND, // 404
    ALARM_ALREADY_ACTIVE, // 409
    ALARM_ALREADY_INACTIVE, // 409
    ALARM_LOCATION_REQUIRES_ROUTINE, // 400

    // ===== REPORT 관련 =====
    REPORT_ALREADY_EXISTS, // 409

    // ===== FCM 관련 =====
    FCM_TOKEN_NOT_FOUND, // 404
    FCM_INVALID_TOKEN, // 400

    DATE_FORMAT_INVALID, // 400
    NUMBER_FORMAT_INVALID, // 400
    ;

    fun toException(): BottariException =
        when (this) {
            // ===== NOT FOUND =====
            MEMBER_NOT_FOUND,
            BOTTARI_NOT_FOUND,
            BOTTARI_ITEM_NOT_FOUND,
            BOTTARI_ITEM_ALREADY_CHECKED,
            BOTTARI_ITEM_ALREADY_UNCHECKED,
            BOTTARI_TEMPLATE_NOT_FOUND,
            TEAM_BOTTARI_NOT_FOUND,
            TEAM_BOTTARI_ITEM_INFO_NOT_FOUND,
            TEAM_MEMBER_NOT_FOUND,
            ALARM_NOT_FOUND,
            -> BottariException.NotFoundException

            // ===== DUPLICATED =====
            MEMBER_NAME_ALREADY_EXISTS,
            MEMBER_SSAID_ALREADY_EXISTS,
            BOTTARI_ITEM_ALREADY_EXISTS,
            BOTTARI_TEMPLATE_ITEM_DUPLICATE_IN_REQUEST,
            TEAM_BOTTARI_ITEM_ALREADY_EXISTS,
            MEMBER_ALREADY_IN_TEAM_BOTTARI,
            TEAM_MEMBER_ALREADY_CHECKED_ALL,
            ALARM_ALREADY_ACTIVE,
            ALARM_ALREADY_INACTIVE,
            REPORT_ALREADY_EXISTS,
            TEAM_BOTTARI_ITEM_ALREADY_CHECKED,
            TEAM_BOTTARI_ITEM_ALREADY_UNCHECKED,
            -> BottariException.DuplicatedException

            // ===== OFFENSIVE =====
            MEMBER_NAME_OFFENSIVE,
            BOTTARI_TITLE_OFFENSIVE,
            ITEM_NAME_OFFENSIVE,
            BOTTARI_TEMPLATE_TITLE_OFFENSIVE,
            -> BottariException.OffensiveException

            // ===== INVALID =====
            MEMBER_NAME_UNCHANGED,
            MEMBER_NAME_TOO_SHORT,
            MEMBER_NAME_TOO_LONG,
            MEMBER_NAME_GENERATION_FAILED,
            MEMBER_IDENTIFIER_NOT_FOUND_IN_REQUEST,
            BOTTARI_TITLE_UNCHANGED,
            BOTTARI_TITLE_BLANK,
            BOTTARI_TITLE_TOO_LONG,
            ITEM_NAME_BLANK,
            ITEM_NAME_TOO_LONG,
            BOTTARI_ITEM_DUPLICATE_IN_REQUEST,
            BOTTARI_ITEM_NOT_IN_BOTTARI,
            BOTTARI_ITEM_CHECK_STATE_INVALID,
            BOTTARI_TEMPLATE_TITLE_BLANK,
            BOTTARI_TEMPLATE_TITLE_TOO_LONG,
            BOTTARI_TEMPLATE_INVALID_SORT_TYPE,
            TEAM_BOTTARI_ITEM_NOT_FOUND,
            TEAM_BOTTARI_ITEM_NAME_BLANK,
            TEAM_BOTTARI_ITEM_NAME_TOO_LONG,
            TEAM_BOTTARI_ITEM_NO_ASSIGNED_MEMBERS,
            TEAM_BOTTARI_ITEM_INAPPROPRIATE_TYPE,
            CANNOT_SEND_REMIND_TO_SELF,
            ALARM_LOCATION_REQUIRES_ROUTINE,
            DATE_FORMAT_INVALID,
            NUMBER_FORMAT_INVALID,
            -> BottariException.InvalidException

            // ===== PERMISSION =====
            BOTTARI_NOT_OWNED,
            BOTTARI_ITEM_NOT_OWNED,
            BOTTARI_TEMPLATE_NOT_OWNED,
            TEAM_BOTTARI_ITEM_NOT_OWNED,
            MEMBER_NOT_IN_TEAM_BOTTARI,
            -> BottariException.PermissionException

            // ===== MAXIMUM =====
            BOTTARI_ITEM_MAXIMUM_EXCEEDED,
            -> BottariException.MaximumExceededException

            // ===== FCM =====
            FCM_TOKEN_NOT_FOUND,
            FCM_INVALID_TOKEN,
            -> BottariException.FcmException
        }
}
